// Chapter-wise practical-lab coverage tracker.
// Run: node scripts/lab-coverage.mjs   (writes docs/completion/lab-coverage-tracker.md and lab-coverage-remaining.json)
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const PACKS = join(root, 'content', 'packs', 'CUET_UG');
const SUBJECTS = [['Physics', '322'], ['Chemistry', '306'], ['Biology', '304'], ['Mathematics', '319'], ['Computer Science', '308'], ['Geography', '313'], ['General Aptitude Test', '501']];

// chapters = lessons
const chapters = [];
for (const [subject, paper] of SUBJECTS) {
  for (const f of readdirSync(join(PACKS, paper)).filter((x) => x.endsWith('.json')).sort()) {
    const d = JSON.parse(readFileSync(join(PACKS, paper, f), 'utf8'));
    if (d.lesson && d.lesson.blocks) chapters.push({ subject, paper, file: f, title: d.lesson.title, headings: d.lesson.blocks.filter((b) => b.type === 'HEADING').map((b) => b.text) });
  }
}

// A quoted string literal in source: 'x', "x" or `x` (no escapes handled beyond \' and \").
const STR = '(\'(?:[^\'\\\\]|\\\\.)*\'|"(?:[^"\\\\]|\\\\.)*"|`[^`]*`)';
const unq = (x) => x.slice(1, -1).replace(/\\'/g, "'").replace(/\\"/g, '"');
const reEntry = new RegExp(`id: '([a-z0-9-]+)',\\s*subject: '([^']+)',[\\s\\S]*?lessonTitleStartsWith: ${STR},\\s*afterHeading: ${STR},[\\s\\S]*?title: ${STR}`, 'g');
const reSpec = new RegExp(`id: '([a-z0-9-]+)',\\s*subject: '([^']+)',\\s*lessonTitleStartsWith: ${STR},\\s*afterHeading: ${STR},\\s*title: ${STR}`, 'g');

const labs = [];
const labsTs = readFileSync(join(root, 'frontend', 'src', 'visual', 'labs.ts'), 'utf8');
const manual = labsTs.slice(labsTs.indexOf('const MANUAL'), labsTs.indexOf('const FROM_SPECS'));
for (const m of manual.matchAll(reEntry)) labs.push({ id: m[1], subject: m[2], prefix: unq(m[3]), heading: unq(m[4]), title: unq(m[5]), kind: 'existing' });
const specDir = join(root, 'frontend', 'src', 'visual', 'specs');
if (existsSync(specDir)) {
  for (const f of readdirSync(specDir).filter((x) => /\.tsx?$/.test(x))) {
    const s = readFileSync(join(specDir, f), 'utf8');
    for (const m of s.matchAll(reSpec)) labs.push({ id: m[1], subject: m[2], prefix: unq(m[3]), heading: unq(m[4]), title: unq(m[5]), kind: 'new' });
  }
}

const rows = chapters.map((c) => {
  const lab = labs.find((l) => l.subject === c.subject && c.title.startsWith(l.prefix));
  return { ...c, lab, headingOk: lab ? c.headings.includes(lab.heading) : false };
});

let md = `# Chapter-wise practical lab coverage tracker\n\nGenerated by \`node scripts/lab-coverage.mjs\` from the content packs (chapters = lessons) and the lab registry. Re-run it after adding labs.\n\n## Summary\n\n| Subject | Chapters | Existing labs mapped | New chapter labs | Chapters without a lab | Coverage |\n|---|---|---|---|---|---|\n`;
const tot = { c: 0, e: 0, n: 0, r: 0 };
for (const [subject] of SUBJECTS) {
  const r = rows.filter((x) => x.subject === subject);
  const e = r.filter((x) => x.lab && x.lab.kind === 'existing').length;
  const n = r.filter((x) => x.lab && x.lab.kind === 'new').length;
  const rem = r.filter((x) => !x.lab).length;
  tot.c += r.length; tot.e += e; tot.n += n; tot.r += rem;
  md += `| ${subject} | ${r.length} | ${e} | ${n} | ${rem} | ${Math.round((100 * (e + n)) / r.length)}% |\n`;
}
md += `| **All seven subjects** | **${tot.c}** | **${tot.e}** | **${tot.n}** | **${tot.r}** | **${Math.round((100 * (tot.e + tot.n)) / tot.c)}%** |\n\n`;
md += `"Chapter" means one lesson of the loaded content (each lesson is attached to one official syllabus row). A lab can serve several chapters (for example one visualiser covers Stack, Queue and Deque, Sorting and Searching).\n`;
for (const [subject] of SUBJECTS) {
  md += `\n## ${subject}\n\n| # | Chapter | Lab | Status |\n|---|---|---|---|\n`;
  rows.filter((x) => x.subject === subject).forEach((x, i) => {
    const status = !x.lab ? '**No lab yet**' : x.lab.kind === 'existing' ? 'Existing lab' : 'New chapter lab';
    md += `| ${i + 1} | ${x.title.replace(/\|/g, '/').slice(0, 90)} | ${x.lab ? `${x.lab.title} (\`${x.lab.id}\`)` : '—'} | ${status}${x.lab && !x.headingOk ? ' (card heading not found)' : ''} |\n`;
  });
}
writeFileSync(join(root, 'docs', 'completion', 'lab-coverage-tracker.md'), md);
writeFileSync(join(root, 'docs', 'completion', 'lab-coverage-remaining.json'), JSON.stringify(rows.filter((x) => !x.lab).map((x) => ({ subject: x.subject, paper: x.paper, file: x.file, title: x.title, headings: x.headings })), null, 1));
console.log(md.split('\n## ')[1]);
const bad = rows.filter((x) => x.lab && !x.headingOk);
if (bad.length) console.log('CARD HEADING NOT FOUND:', bad.map((x) => x.title));

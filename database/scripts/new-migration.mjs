// Create the next D1 migration from changes in prisma/schema.prisma.
//
// Usage: npm run db:migration:new -- <short_name>
//
// How it works (Prisma Migrate itself does not support D1):
// 1. Build a scratch SQLite database by running every existing migrations/*.sql file in order
//    (Node's built-in node:sqlite, no extra install).
// 2. Ask `prisma migrate diff` for the SQL that turns that database into the current schema.
// 3. Write it to migrations/NNNN_<short_name>.sql for review. Apply it with
//    `npm run db:migrate:local` (Wrangler), never by hand on a remote database.
import { DatabaseSync } from 'node:sqlite';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const name = (process.argv[2] ?? '').trim();
if (!/^[a-z0-9_]{3,60}$/.test(name)) {
  console.error('Give a short snake_case name, e.g. npm run db:migration:new -- add_question_tags');
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(root, 'migrations');
const files = readdirSync(migrationsDir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
const next = String(files.length ? Number(files.at(-1).slice(0, 4)) + 1 : 1).padStart(4, '0');

const scratchDir = join(root, '.local');
mkdirSync(scratchDir, { recursive: true });
const scratch = join(scratchDir, 'migration-base.sqlite');
rmSync(scratch, { force: true });
const db = new DatabaseSync(scratch);
for (const f of files) db.exec(readFileSync(join(migrationsDir, f), 'utf8'));
db.close();

const out = execFileSync(
  process.platform === 'win32' ? 'npx.cmd' : 'npx',
  ['prisma', 'migrate', 'diff', '--from-config-datasource', '--to-schema', 'prisma/schema.prisma', '--script'],
  { cwd: root, env: { ...process.env, DATABASE_URL: `file:${scratch}` }, encoding: 'utf8', shell: process.platform === 'win32' },
);
const sql = out.replace(/^Loaded Prisma config.*\n/m, '').trim();
if (!sql || /^-- This is an empty migration/.test(sql)) {
  console.log('No schema changes found. Nothing written.');
  process.exit(0);
}
const target = join(migrationsDir, `${next}_${name}.sql`);
writeFileSync(target, `-- Generated by database/scripts/new-migration.mjs. Review before applying.\n${sql}\n`);
console.log(`Wrote ${target}`);
if (/DROP TABLE|DROP COLUMN|ALTER TABLE .* RENAME/i.test(sql)) {
  console.warn('WARNING: this migration drops or rebuilds tables. Back up D1 (Time Travel or export) before applying remotely.');
}
